    private void removeSelectedServiceAlertButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeSelectedServiceAlertButtonActionPerformed
        // TODO add your handling code here:
        if (vehicleSelectComboBox.getSelectedItem() == null || lineSelectComboBox.getSelectedItem() == null){
            JOptionPane.showMessageDialog(this, "There is no existing route available.\nPlease use Remove All fuction instead.");
            return;
        }
        
        String vehicleType = vehicleSelectComboBox.getSelectedItem().toString();
        String lineName = lineSelectComboBox.getSelectedItem().toString();
        System.out.println(vehicleType + " " + lineName);
        
        int answer = JOptionPane.showConfirmDialog(this, "Are you sure to remove all service alerts associated with " + vehicleType + " line named " + lineName + "?\nThis action cannot be undone.", "Remove an Existing Service Alert" ,JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        
        if (answer == JOptionPane.YES_OPTION) {
            ArrayList<String> remainingServiceAlerts = new ArrayList<>();
            boolean isRemoved = false;
            try (BufferedReader reader = new BufferedReader(new FileReader("servicealerts.txt"))) {
                String line;
                while ((line = reader.readLine()) != null) {
                    String[] parts = line.split(";");

                    if (parts.length >= 2 && parts[0].equals(vehicleType) && parts[1].equals(lineName)) {
                        isRemoved = true;
                    } else {
                        remainingServiceAlerts.add(line);
                    }
                }
            } catch (IOException e) {
                JOptionPane.showMessageDialog(this, "Error occured in reading file: " + e.getMessage());
            }
            
            if (isRemoved) {
                try (BufferedWriter writer = new BufferedWriter(new FileWriter("servicealerts.txt", false))) {
                    
                    for (int i = 0; i < remainingServiceAlerts.size(); i++) {
                        writer.write(remainingServiceAlerts.get(i));
                        writer.newLine();
                    } 

                } catch (IOException e) {
                    JOptionPane.showMessageDialog(this, "Error occured in writing to file: " + e.getMessage());
                }
                JOptionPane.showMessageDialog(this, "The service alerts associated with " + vehicleType + " route " + lineName + " have been removed successfully.");
            } else {
                JOptionPane.showMessageDialog(this, "Could not find any alert associated with the selected route in the file.");
            }
        }
    }//GEN-LAST:event_removeSelectedServiceAlertButtonActionPerformed

