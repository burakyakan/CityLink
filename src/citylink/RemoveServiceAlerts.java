    private void removeAllServiceAlertsButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeAllServiceAlertsButtonActionPerformed
        // TODO add your handling code here:
        int answer = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to remove all existing service alerts?\nThis action cannot be undone.",
                "Remove All Existing Service Alerts",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.WARNING_MESSAGE);

        if (answer == javax.swing.JOptionPane.YES_OPTION) {
            
            try (BufferedWriter writer = new BufferedWriter(new FileWriter("servicealerts.txt", false))) {
                writer.write("");
                writer.newLine();
                javax.swing.JOptionPane.showMessageDialog(this, "All existing service alerts have been removed successfully.");

            } catch (IOException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "File Error: " + e.getMessage());

            }

        }
    }//GEN-LAST:event_removeAllServiceAlertsButtonActionPerformed

